"""Prepare the native RP6502 image from the extracted game asset.

The optional extract_assets.py uses unpack() to run the original depacker.
Ordinary builds use only Python's standard library and the saved native data.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct
import sys
from native_assets import load_asset, load_manifest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'build/python-deps'))
SOURCE_SHA = '3796ab51067e55489d42b7be27c1a9d83a7ed19e9be7cbed8889474747110b5c'
ATARI_HZ = 1_773_447
PSG_GAINS = (256, 204, 168, 142, 120, 102, 86, 73, 61, 50, 40, 31, 22, 14, 7, 0)


def audio_levels():
    # Linear POKEY DAC -> closest logarithmic PSG attenuation. 120/256
    # maximum per oscillator leaves >7% stereo mixer headroom with all four
    # voices at full volume, including simultaneous music and both spies.
    return [min(range(16), key=lambda level: abs(PSG_GAINS[level]-volume*8)) << 4
            for volume in range(16)]


def delay_ticks(count, long=False):
    """Cycles in the original delay loops, including count=0's wrap to 256."""
    count = count or 256
    cycles = count * (328714 if long else 1284) + 23
    return (cycles * 60 + ATARI_HZ - 1) // ATARI_HZ


def patch_timing(memory, labels):
    # Verify instruction boundaries before redirecting original entry points.
    for address, expected, opcode, target in [
        (0x0ceb, 'ad8103', 0x20, 'pace_main'),
        (0x2e94, '8e6d03', 0x4c, 'delay_short'),
        (0x2ea9, '8e6d03', 0x4c, 'delay_long'),
    ]:
        if memory[address:address+3] != bytes.fromhex(expected):
            raise ValueError(f'Timing patch anchor differs at ${address:04X}')
        memory[address:address+3] = bytes([opcode]) + struct.pack('<H', labels[target])


def segments(data):
    if data[:2] != b'\xff\xff':
        raise ValueError('Not an Atari XEX')
    pos = 2
    while pos < len(data):
        if pos + 2 > len(data):
            raise ValueError('Truncated segment header')
        start = struct.unpack_from('<H', data, pos)[0]
        pos += 2
        if start == 0xffff:
            continue
        if pos + 2 > len(data):
            raise ValueError('Truncated segment end')
        end = struct.unpack_from('<H', data, pos)[0]
        pos += 2
        size = end - start + 1
        if size <= 0 or pos + size > len(data):
            raise ValueError('Invalid or truncated segment')
        yield start, data[pos:pos + size]
        pos += size


def patch_music(memory, labels):
    if memory[0x7550:0x7553] != bytes.fromhex('20ea34'):
        raise ValueError('Music patch anchor differs at $7550')
    memory[0x7550:0x7553] = b'\x20' + struct.pack('<H', labels['music_tick'])


def unpack(data):
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA:
        raise ValueError('This port requires the inspected HOMESOFT SpyVsSpy.xex; SHA-256 differs')
    from py65.devices.mpu6502 import MPU
    cpu = MPU()
    for start, block in segments(data):
        cpu.memory[start:start + len(block)] = block
    cpu.pc = cpu.memory[0x2e2] | cpu.memory[0x2e3] << 8
    for step in range(2_000_000):
        if cpu.pc == 0x0c00:
            break
        if step % 100 == 0:
            cpu.memory[0x14] = (cpu.memory[0x14] + 1) & 255
        if cpu.disassemble[cpu.memory[cpu.pc]][0] == '???':
            raise ValueError(f'Invalid depacker opcode at ${cpu.pc:04X}')
        cpu.step()
    else:
        raise ValueError('Depacker did not reach the game entry')
    # Retain actual depacked regions, not the obsolete packed input/loader.
    memory = bytearray(65536)
    memory[0x400:0xbb80] = bytes(cpu.memory[0x400:0xbb80])
    memory[0xe400:0xff00] = bytes(cpu.memory[0xe400:0xff00])
    return memory, step


def atari_color(index):
    hue, lum = index >> 4, (index & 14) / 14
    if hue == 0:
        r = g = b = lum
    else:
        angle = 2.6 - (hue - 1) * 2 * math.pi / 15
        u, v = math.cos(angle) * .22, math.sin(angle) * .22
        r, g, b = lum + 1.14*v, lum-.395*u-.581*v, lum+2.032*u
    rgb = [round(max(0, min(1, c)) * 31) for c in (r, g, b)]
    return rgb[0] | rgb[1] << 6 | rgb[2] << 11 | 0x20


def tables(out):
    # Approximate Atari hues in RGB555; explicit rather than firmware palette.
    colors = [atari_color(index) for index in range(256)]
    lines = ['; Generated by prepare_spy.py', '.segment "TABLES"']
    for name, values in [('color_lo', [c & 255 for c in colors]),
                         ('color_hi', [c >> 8 for c in colors]),
                         ('freq_lo', [min(65535, round(3*ATARI_HZ/(56*(i+1)))) & 255 for i in range(256)]),
                         ('freq_hi', [min(65535, round(3*ATARI_HZ/(56*(i+1)))) >> 8 for i in range(256)])]:
        lines.append(name + ':')
        for i in range(0, 256, 16):
            lines.append(' .byte ' + ','.join(str(x) for x in values[i:i+16]))
    lines.extend(['audio_levels:', ' .byte ' + ','.join(str(x) for x in audio_levels())])
    for name, values, segment in [
        ('short_ticks', [delay_ticks(i) for i in range(256)], 'TABLES'),
        ('long_ticks_lo', [delay_ticks(i, True) & 255 for i in range(256)], 'CODE'),
        ('long_ticks_hi', [delay_ticks(i, True) >> 8 for i in range(256)], 'CODE'),
    ]:
        lines.extend([f'.segment "{segment}"', name + ':'])
        for i in range(0, 256, 16):
            lines.append(' .byte ' + ','.join(str(x) for x in values[i:i+16]))
    (out/'tables.inc').write_text('\n'.join(lines)+'\n', encoding='ascii')
    backdrop(out)


def patch_cable_extensions(memory):
    """Bridge the two-pixel gap from each cable's left end to its monitor.

    The first color-clock pixel of column 29 is exterior fill in the XEX.
    Copy the adjacent cable pixel (blue PMG showing through, or black edge).
    Keep the monitor at x<232 and all original cable pixels intact.
    """
    for top in (111, 207):
        for screen_y in range(top, top+7):
            y = screen_y-20
            offset = (y//24)*1024+((y%24)//8*40+29)*8+y%8
            address = 0x9400+offset
            original = memory[address]
            if original >> 6 != 2:
                raise ValueError(f'Unexpected cable extension pixel at ${address:04X}')
            memory[address] = (original & 0x3f) | ((original & 0x30) << 2)


def backdrop(out):
    """Build a black overlay around the static cabinet silhouettes.

    Each run stores row count and two half-open spans: monitor and side panel.
    Bounds use two-pixel Atari color-clock units. Outside those bounds, mask
    only background-color pixels from the original artwork, preserving the
    bezel and cable outlines. The overlay sits above the glyph plane.
    """
    runs = []
    for y in range(20, 220):
        if y < 28:
            left, right = 28-y, y+88
        elif y == 119:
            left, right = 1, 116
        elif 120 <= y < 124:
            left, right = 124-y, y-8
        elif y == 216:
            left, right = 11, 106
        elif y > 216:
            left, right = 0, 0
        else:
            left, right = 0, 116
        panel_left = panel_right = 0
        for top in (28, 124):
            row = y-top
            if row == 0:
                panel_left, panel_right = 152, 156
            elif row in (1, 2, 3, 4):
                # Only the raised connector encloses background pixels here;
                # the long gap above the sloping panel edge is exterior.
                panel_left, panel_right = 151, 157
            elif 5 <= row <= 6:
                panel_left, panel_right = 123-row, 153+row
            elif 7 <= row <= 67:
                panel_left, panel_right = 116, 160
            elif 68 <= row <= 71:
                panel_left, panel_right = row+48, 227-row
            # Rows 72/73 are below the panel: its bevel and cable survive
            # through their original non-background pixels, not a filled span.
        spans = [left, right, panel_left, panel_right]
        if runs and runs[-1][1:] == spans:
            runs[-1][0] += 1
        else:
            runs.append([1]+spans)
    # Pixel value 2 is the original exterior fill. Other pixels belong to
    # cabinet outlines and cables and must remain visible above the mask.
    memory = bytearray((out/'original.bin').read_bytes())
    patch_cable_extensions(memory)
    bitmap = bytearray()
    for count, left, right, panel_left, panel_right in runs:
        for _ in range(count):
            y = len(bitmap)//40
            for column in range(40):
                value = 0
                for pixel in range(8):
                    x = column*8+pixel
                    offset = (y//24)*1024+((y%24)//8*40+x//8)*8+y%8
                    color = (memory[0x9400+offset] >> (6-2*((x%8)//2))) & 3
                    inside = left <= x//2 < right or panel_left <= x//2 < panel_right
                    value = value*2 + (not inside and color == 2)
                bitmap.append(value)
    # 1..127: zero run; 129..255: FF run; 128: literal byte; 0: end.
    encoded = []
    pos = 0
    while pos < len(bitmap):
        value = bitmap[pos]
        if value not in (0, 255):
            encoded.extend((128, value))
            pos += 1
            continue
        count = 1
        while pos+count < len(bitmap) and bitmap[pos+count] == value and count < 127:
            count += 1
        encoded.append(count | (128 if value else 0))
        pos += count
    encoded.append(0)
    lines = ['; Generated static exterior mask, zero/FF runs and literals.', 'backdrop_runs:']
    lines += [' .byte '+','.join(map(str, encoded[i:i+16])) for i in range(0, len(encoded), 16)]
    (out/'backdrop.inc').write_text('\n'.join(lines)+'\n', encoding='ascii')



def analysis_report(memory, steps, data):
    report = {'source_sha256': SOURCE_SHA, 'depacker_instructions': steps,
              'entry': '0C00', 'segments': [dict(start=f'{s:04X}', size=len(b)) for s,b in segments(data)],
              'overlays': []}
    for i in range(5):
        report['overlays'].append(dict(index=i,
            source=f'{memory[0xe476+i] | memory[0xe47b+i]<<8:04X}',
            destination=f'{memory[0x2a5e+i] | memory[0x2a63+i]<<8:04X}',
            size=128*memory[0x2a68+i]))
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--link', action='store_true')
    args = parser.parse_args()
    out = args.output
    out.mkdir(parents=True, exist_ok=True)
    if args.link:
        memory = bytearray((out/'original.bin').read_bytes())
        patch_cable_extensions(memory)
        labels = {}
        for line in (out/'host.lbl').read_text().splitlines():
            fields = line.split()
            if len(fields) == 3:
                labels[fields[2].lstrip('.')] = int(fields[1], 16)
        host = (out/'host.bin').read_bytes()
        host_tables = (out/'host.bin.tables').read_bytes()
        if len(host) != 0x1000 or len(host_tables) != 0x0bfc:
            raise ValueError('Unexpected host layout; refusing to resize the game memory')
        memory[0xc000:0xd000] = host
        memory[0xd800:0xe3fc] = host_tables
        # SETVBV is the only OS service used during boot/gameplay observed so far.
        memory[0xe45c:0xe45f] = b'\x4c' + struct.pack('<H', labels['setvbv'])
        patch_timing(memory, labels)
        patch_music(memory, labels)
        (out/'spy.bin').write_bytes(memory[:0xff00])
    else:
        memory = load_asset(args.source)
        (out/'original.bin').write_bytes(memory)
        report = load_manifest(args.source.parent)['game_analysis']
        (out/'analysis.json').write_text(json.dumps(report, indent=2)+'\n')
        tables(out)


if __name__ == '__main__':
    main()
